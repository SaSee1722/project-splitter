function generateFlutterStructure(zip: JSZip, input: ProjectInput, screens: ScreenItem[]) {
  const lib = zip.folder('lib');
  const screensFolder = lib?.folder('screens');
  lib?.folder('widgets');
  lib?.folder('models');
  lib?.folder('services');

  screens.forEach((screen) => {
    const safeName = screen.name.toLowerCase().replace(/[^a-z0-9]/g, '_');
    screensFolder?.file(`${safeName}_screen.dart`, createFlutterScreenPlaceholder(screen));
  });

  lib?.file(
    'main.dart',
    `import 'package:flutter/material.dart';

void main() {
  runApp(const MyApp());
}

class MyApp extends StatelessWidget {
  const MyApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: '${input.projectName}',
      home: Scaffold(
        appBar: AppBar(title: const Text('${input.projectName}')),
        body: const Center(child: Text('TeamForge AI Starter')),
      ),
    );
  }
}
`
  );

  zip.file(
    'pubspec.yaml',
    `name: ${input.projectName.toLowerCase().replace(/[^a-z0-9]/g, '_')}
description: "${input.projectName} starter project."
version: 1.0.0+1
environment:
  sdk: '>=3.0.0 <4.0.0'
dependencies:
  flutter:
    sdk: flutter
`
  );
}

function generateNodeStructure(zip: JSZip, input: ProjectInput, screens: ScreenItem[]) {
  const src = zip.folder('src');
  const routesFolder = src?.folder('routes');
  src?.folder('controllers');
  src?.folder('services');
  src?.folder('middlewares');

  screens.forEach((screen) => {
    const slug = screen.name.toLowerCase().replace(/[^a-z0-9]/g, '-');
    routesFolder?.file(`${slug}.router.ts`, createNodeRoutePlaceholder(screen));
  });

  src?.file(
    'index.ts',
    `import express from 'express';

const app = express();
app.use(express.json());

const PORT = process.env.PORT || 4000;
app.listen(PORT, () => {
  console.log(\`Server running for ${input.projectName} on port \${PORT}\`);
});
`
  );
}

