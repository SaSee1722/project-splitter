import JSZip from 'jszip';
import { ProjectBlueprint, ProjectInput, ScreenItem } from '@/types/project';

export async function generateProjectZip(
  input: ProjectInput,
  blueprint: ProjectBlueprint
): Promise<Blob> {
  const zip = new JSZip();
  const tech = input.technology.toLowerCase();

  // 1. Root README.md
  zip.file('README.md', generateReadmeContent(input, blueprint));

  // 2. TEAM_ASSIGNMENTS.md
  zip.file('TEAM_ASSIGNMENTS.md', generateTeamAssignmentsContent(input, blueprint));

  // 3. GIT_WORKFLOW.md
  zip.file('GIT_WORKFLOW.md', generateGitWorkflowContent(blueprint));

  // Combine regular screens and AI suggested screens
  const allScreens: ScreenItem[] = [
    ...blueprint.screens,
    ...(blueprint.aiSuggestedScreens || []).map((s) => ({
      ...s,
      isAiSuggested: true,
    })),
  ];

  // 4. Framework specific file generation
  if (tech.includes('flutter')) {
    generateFlutterStructure(zip, input, allScreens);
  } else if (tech.includes('next')) {
    generateNextjsStructure(zip, input, allScreens);
  } else if (tech.includes('react native')) {
    generateReactNativeStructure(zip, input, allScreens);
  } else if (tech.includes('node')) {
    generateNodeStructure(zip, input, allScreens);
  } else {
    // Standard React / Vite
    generateReactStructure(zip, input, allScreens);
  }

  return await zip.generateAsync({ type: 'blob' });
}

function generateReactStructure(zip: JSZip, input: ProjectInput, screens: ScreenItem[]) {
  const src = zip.folder('src');
  const screensFolder = src?.folder('screens');
  src?.folder('components');
  src?.folder('navigation');
  src?.folder('services');
  src?.folder('hooks');
  src?.folder('types');

  screens.forEach((screen) => {
    const safeName = screen.name.replace(/[^a-zA-Z0-9]/g, '');
    const fileName = `${safeName}Screen.tsx`;
    screensFolder?.file(fileName, createReactScreenPlaceholder(screen));
  });

  src?.file(
    'App.tsx',
    `import React from 'react';

/**
 * Main Application Routing Skeleton
 * Project: ${input.projectName}
 * Generated by TeamForge AI
 */
export default function App() {
  return (
    <div style={{ padding: 32, fontFamily: 'sans-serif' }}>
      <h1>${input.projectName}</h1>
      <p>Project skeleton generated by TeamForge AI.</p>
      {/* Route your screen placeholders here */}
    </div>
  );
}
`
  );

  zip.file(
    'package.json',
    JSON.stringify(
      {
        name: input.projectName.toLowerCase().replace(/[^a-z0-9]/g, '-'),
        version: '0.1.0',
        private: true,
        scripts: {
          dev: 'vite',
          build: 'tsc && vite build',
          lint: 'eslint .',
        },
        dependencies: {
          react: '^18.3.1',
          'react-dom': '^18.3.1',
        },
      },
      null,
      2
    )
  );
}

